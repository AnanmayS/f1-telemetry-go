// Command bench measures the storage engine against the ingested corpus:
// compression, decode throughput and single-lap lookup latency. Every number
// in docs/BENCHMARKS.md and the README comes from this program.
package main

import (
	"flag"
	"fmt"
	"io"
	"log/slog"
	"math/rand"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"time"

	"github.com/AnanmayS/f1-telemetry-go/internal/model"
	"github.com/AnanmayS/f1-telemetry-go/internal/segment"
	"github.com/AnanmayS/f1-telemetry-go/internal/store"
)

type lapRef struct{ session, driver, lap int }

func main() {
	dataDir := flag.String("data", "data", "data directory")
	lookups := flag.Int("lookups", 20000, "single-lap lookups to time for each of cold and warm")
	seed := flag.Int64("seed", 1, "random seed for lap selection")
	flag.Parse()

	man, err := store.LoadManifest(*dataDir)
	if err != nil || len(man.Segments) == 0 {
		fmt.Fprintf(os.Stderr, "bench: no segments in %s (run cmd/ingest first): %v\n", *dataDir, err)
		os.Exit(1)
	}

	// Pass 1: sizes and a full decode of every block.
	var (
		samples, rawSamples, rawJSON, segBytes, nLaps, nBlocks int64
		chBytes, chCount                                       [model.NumChannels]int64
		decoded                                                int64
		decodeTime                                             time.Duration
		refs                                                   []lapRef
		years                                                  = map[int]int{}
	)
	for _, e := range man.Segments {
		seg, err := segment.Open(filepath.Join(*dataDir, store.SegmentDir, e.File))
		if err != nil {
			fmt.Fprintln(os.Stderr, "bench: skipping", e.File, err)
			continue
		}
		years[e.Year]++
		samples += seg.Meta.Samples
		rawSamples += seg.Meta.RawSamples
		rawJSON += seg.Meta.RawJSONBytes
		segBytes += int64(seg.Size())
		for _, b := range seg.Blocks() {
			chBytes[b.Channel] += int64(b.Length)
			chCount[b.Channel] += int64(b.Count)
			nBlocks++
		}
		for _, l := range seg.AllLaps() {
			nLaps++
			if l.Samples == 0 {
				continue
			}
			refs = append(refs, lapRef{e.SessionKey, l.Driver, l.Number})
			start := time.Now()
			ld, err := seg.ReadLap(l.Driver, l.Number)
			decodeTime += time.Since(start)
			if err != nil {
				fmt.Fprintln(os.Stderr, "bench: decode error:", err)
				continue
			}
			decoded += int64(ld.Lap.Samples) * int64(model.NumChannels)
		}
		seg.Close()
	}
	values := samples * int64(model.NumChannels)

	// Pass 2: lookup latency through the store (index search + decode + cache).
	quiet := slog.New(slog.NewTextHandler(io.Discard, nil))
	st, err := store.Open(*dataDir, 1<<30, quiet)
	if err != nil {
		fmt.Fprintln(os.Stderr, "bench:", err)
		os.Exit(1)
	}
	defer st.Close()
	rng := rand.New(rand.NewSource(*seed))
	rng.Shuffle(len(refs), func(i, j int) { refs[i], refs[j] = refs[j], refs[i] })
	n := min(*lookups, len(refs))
	pick := refs[:n]
	timeLookups := func() []time.Duration {
		out := make([]time.Duration, 0, n)
		for _, r := range pick {
			start := time.Now()
			sess, err := st.Acquire(r.session)
			if err == nil {
				_, err = st.Lap(sess, r.driver, r.lap)
				sess.Release()
			}
			out = append(out, time.Since(start))
			if err != nil {
				fmt.Fprintln(os.Stderr, "bench: lookup error:", err)
			}
		}
		sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
		return out
	}
	cold := timeLookups() // each lap is decoded from the mapped file for the first time
	warm := timeLookups() // the same laps again, now in the lap cache
	stats := st.Stats()

	fmt.Printf("## Storage benchmark\n\n")
	fmt.Printf("Generated by `go run ./cmd/bench` on %s (%s/%s, %d CPUs, %s).\n\n",
		time.Now().UTC().Format("2006-01-02"), runtime.GOOS, runtime.GOARCH, runtime.NumCPU(), runtime.Version())

	fmt.Printf("### Corpus\n\n| Metric | Value |\n|---|---|\n")
	ys := make([]int, 0, len(years))
	for y := range years {
		ys = append(ys, y)
	}
	sort.Ints(ys)
	perYear := ""
	for i, y := range ys {
		if i > 0 {
			perYear += ", "
		}
		perYear += fmt.Sprintf("%d: %d", y, years[y])
	}
	fmt.Printf("| Sessions | %d (%s) |\n", len(man.Segments), perYear)
	fmt.Printf("| Sessions skipped (no telemetry) | %d |\n", len(man.Skipped))
	fmt.Printf("| Laps | %s |\n", commas(nLaps))
	fmt.Printf("| Samples stored (inside laps) | %s |\n", commas(samples))
	fmt.Printf("| Values stored (%d channels) | %s |\n", model.NumChannels, commas(values))
	fmt.Printf("| Telemetry rows fetched | %s |\n", commas(rawSamples))
	fmt.Printf("| Blocks | %s |\n", commas(nBlocks))

	fmt.Printf("\n### Compression\n\n| Metric | Value |\n|---|---|\n")
	fmt.Printf("| Raw API JSON fetched | %s |\n", size(rawJSON))
	fmt.Printf("| Segment files | %s |\n", size(segBytes))
	fmt.Printf("| Ratio vs all raw JSON fetched | %.1fx |\n", ratio(rawJSON, segBytes))
	// Segments keep only samples inside laps. Scaling the raw size by the
	// stored fraction compares like with like.
	likeForLike := float64(rawJSON) * float64(samples) / float64(max(rawSamples, 1))
	fmt.Printf("| Ratio vs raw JSON of the stored samples only (pro-rated) | %.1fx |\n", likeForLike/float64(segBytes))
	fmt.Printf("| Ratio vs raw 8-byte integers | %.1fx |\n", ratio(values*8, segBytes))
	fmt.Printf("| Bytes per sample (all channels, incl. index) | %.2f |\n", float64(segBytes)/float64(max(samples, 1)))

	fmt.Printf("\n| Channel | Bytes | Bytes/sample |\n|---|---|---|\n")
	for c := model.Channel(0); c < model.NumChannels; c++ {
		fmt.Printf("| `%s` | %s | %.3f |\n", c, commas(chBytes[c]), float64(chBytes[c])/float64(max(chCount[c], 1)))
	}

	fmt.Printf("\n### Decode and lookup (single thread)\n\n| Metric | Value |\n|---|---|\n")
	fmt.Printf("| Full-corpus decode | %s values in %s |\n", commas(decoded), decodeTime.Round(time.Millisecond))
	fmt.Printf("| Decode throughput | %s values/s (%s samples/s across %d channels) |\n",
		commas(int64(float64(decoded)/decodeTime.Seconds())), commas(int64(float64(decoded)/float64(model.NumChannels)/decodeTime.Seconds())), model.NumChannels)
	fmt.Printf("| Lap lookup, cold (not in lap cache; index search + CRC + decode of %d blocks) | p50 %s, p99 %s, max %s |\n",
		model.NumChannels, pct(cold, 50), pct(cold, 99), cold[len(cold)-1])
	fmt.Printf("| Lap lookup, warm (lap cache hit) | p50 %s, p99 %s, max %s |\n", pct(warm, 50), pct(warm, 99), warm[len(warm)-1])
	fmt.Printf("| Lookups timed | %s cold + %s warm, random laps, seed %d |\n", commas(int64(n)), commas(int64(n)), *seed)
	fmt.Printf("| Lap cache after run | %s in %s laps |\n", size(stats.CacheBytes), commas(stats.Decodes))
	fmt.Printf("\n\"Cold\" means cold for the lap cache. The file pages were already read once by the decode pass, so this excludes disk I/O.\n")
}

func ratio(a, b int64) float64 { return float64(a) / float64(max(b, 1)) }

func pct(d []time.Duration, p int) time.Duration {
	if len(d) == 0 {
		return 0
	}
	return d[min(len(d)*p/100, len(d)-1)]
}

func size(b int64) string {
	switch {
	case b >= 1<<30:
		return fmt.Sprintf("%.2f GiB", float64(b)/(1<<30))
	case b >= 1<<20:
		return fmt.Sprintf("%.2f MiB", float64(b)/(1<<20))
	}
	return fmt.Sprintf("%.1f KiB", float64(b)/(1<<10))
}

func commas(n int64) string {
	s := fmt.Sprint(n)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}
