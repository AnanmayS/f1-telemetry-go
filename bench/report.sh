#!/usr/bin/env bash
# Regenerates docs/BENCHMARKS.md from scratch: storage benchmark, golden
# correctness run, live-path replay and the HTTP load test. Every number in
# the README comes from this file's output.
#
#   bench/report.sh            # uses ./data
#   DATA=/path bench/report.sh
#
# Needs: go, vegeta, curl, python3. Takes about 6 minutes.
set -euo pipefail
cd "$(dirname "$0")/.."
DATA=${DATA:-data}
OUT=docs/BENCHMARKS.md
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

{
  echo "# Benchmarks"
  echo
  echo "Generated by \`bench/report.sh\` on $(date -u +%Y-%m-%d). Do not edit by hand; rerun the script."
  echo
  echo "Machine: $(uname -sm), $(getconf _NPROCESSORS_ONLN 2>/dev/null || sysctl -n hw.ncpu) CPUs, $(go version | awk '{print $3}'). This is a development laptop that was running other work, not the target VPS; treat latency figures as indicative and rerun on the deployment host."
  echo
  go run ./cmd/bench -data "$DATA"
  echo
  echo "## Correctness against official timing (golden sessions)"
  echo
  echo "\`GHOSTLAP_DATA=$DATA go test ./internal/ingest -run Golden -v\`. One qualifying and one race per season. Each line: lap counts match the laps endpoint, sliced durations match official times, each driver's fastest lap matches the official fastest, and comparing every driver's fastest lap with the session's fastest gives a final delta equal to the official difference."
  echo
  echo '```'
  GHOSTLAP_DATA="$PWD/$DATA" go test ./internal/ingest -run Golden -v -count=1 2>&1 | grep -E "^\s+--- |golden_test.go" | sed -E 's/^ +golden_test.go:[0-9]+: /    /'
  echo '```'
  echo
  echo "The final delta is exact by construction: a lap's distance is normalised so it reaches the circuit length at its official lap time. Mid-lap delta accuracy is limited by the feed (about 3.7 Hz, integer km/h, lap start times good to a few tens of ms)."
  echo
  echo "## Live path"
  echo
  go build -o bin/replay ./cmd/replay
  mkdir -p "$TMP/live/raw"
  ln -s "$PWD/$DATA/raw/9492" "$TMP/live/raw/9492"
  ln -s "$PWD/$DATA/raw/_meta" "$TMP/live/raw/_meta"
  start=$(python3 -c 'import time; print(time.time())')
  ./bin/replay -data "$TMP/live" -year 2024 -session 9492 -speed 0 2> "$TMP/replay.log" | tail -1 > "$TMP/replay.out"
  end=$(python3 -c 'import time; print(time.time())')
  events=$(grep -o 'events=[0-9]*' "$TMP/replay.log" | head -1 | cut -d= -f2)
  python3 - "$events" "$start" "$end" "$(cat "$TMP/replay.out")" <<'PY'
import sys
events, start, end, last = int(sys.argv[1]), float(sys.argv[2]), float(sys.argv[3]), sys.argv[4]
print(f"Replaying session 9492 (2024 Japan qualifying) through WAL, memtable and seal at unlimited speed, fsync every 100 ms: **{events:,} events in {end-start:.2f} s** including process start and loading the raw cache (final line: `{last}`).")
PY
  echo
  echo '`go test ./internal/live -run "Crash|Visible" -v`:'
  echo
  echo '```'
  go test ./internal/live -run 'Crash|Visible' -v -count=1 2>&1 | grep -E "live_test.go|^--- " | sed -E 's/^ +live_test.go:[0-9]+: /    /'
  echo '```'
  echo
  echo "The crash test kills the process with SIGKILL. That proves recovery from a process crash; it does not simulate power loss, where durability also depends on the disk honouring fsync."
  echo
  echo "## HTTP load test: /api/compare"
  echo
  echo "\`bench/load/run.sh\`: vegeta, 20 s per rate, 80% of requests drawn from popular comparisons (fastest laps of the top 5 drivers in the 4 newest sessions) and 20% from random lap pairs across up to 60 sessions. Each rate starts a fresh server with empty caches. Client and server share the machine over loopback, so client-side percentiles include the load generator's own scheduling. \"Server-side <= 50 ms\" is read from the server's Prometheus histogram."
  echo
  echo "### All CPUs"
  echo
  DATA="$DATA" bench/load/run.sh 2>"$TMP/load.log"
  echo
  sed 's/^gentargets: /Target mix: /' "$TMP/load.log" | tail -1
  echo
  echo "### Server limited to 2 CPUs (GOMAXPROCS=2), approximating a small VPS"
  echo
  PROCS=2 RATES="${RATES2:-250 500 1000 2000}" DATA="$DATA" bench/load/run.sh 2>/dev/null
  echo
  echo "### One warm request, in process"
  echo
  echo '`go test ./internal/api -run xxx -bench CompareWarm -benchtime 3s -cpu 1` (response cache bypassed: resample, JSON and gzip on every call):'
  echo
  echo '```'
  GHOSTLAP_DATA="$PWD/$DATA" go test ./internal/api -run xxx -bench CompareWarm -benchtime 3s -cpu 1 2>&1 | grep Benchmark
  echo '```'
} > "$TMP/report.md"
mv "$TMP/report.md" "$OUT"
echo "wrote $OUT" >&2
