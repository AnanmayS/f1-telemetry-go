#!/usr/bin/env bash
# Regenerates docs/PREDICTIONS.md and data/predictions.json.gz from the race
# records. Every accuracy number about predictions comes from this output.
#
#   bench/predict-report.sh          # uses ./data; fetches race metadata first
#   OFFLINE=1 bench/predict-report.sh  # raw cache only
set -euo pipefail
cd "$(dirname "$0")/.."
DATA=${DATA:-data}
RUNS=${RUNS:-2000}
OUT=docs/PREDICTIONS.md
go build -o bin/predict ./cmd/predict
./bin/predict fetch -data "$DATA" ${OFFLINE:+-offline}
{
  cat docs/predictions-head.md
  echo
  echo "## Backtest"
  echo
  echo "Generated by \`bench/predict-report.sh\` on $(date -u +%Y-%m-%d). Do not edit below this line by hand; rerun the script."
  echo
  ./bin/predict backtest -data "$DATA" -runs "$RUNS"
  echo
  echo "## Race by race"
  echo
  echo "The favourite, the pole sitter and the winner of every predicted race, with the win chance each was given."
  echo
  ./bin/predict picks -data "$DATA" -runs "$RUNS"
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
./bin/predict build -data "$DATA" -runs "$RUNS"
echo "wrote $OUT"
